// Copies the Android app's texts, icons and sign-in background into this project, so both apps
// stay the same. Run again after the Android resources change:
//   node scripts/import-android-resources.mjs
import { copyFileSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const res = join(root, '../jellycast-android-tv/tv/src/main/res')
// Genre names moved to the shared module, which both Android apps use.
const coreRes = join(root, '../jellycast-android-tv/core/src/main/res')
const languages = { en: 'values', nl: 'values-nl', fr: 'values-fr', es: 'values-es' }

function decode(text) {
    return text
        .replace(/<!\[CDATA\[([\s\S]*?)\]\]>/g, '$1')
        .replace(/\\'/g, "'")
        .replace(/\\"/g, '"')
        .replace(/\\n/g, '\n')
        .replace(/\\@/g, '@')
        .replace(/&lt;/g, '<')
        .replace(/&gt;/g, '>')
        .replace(/&quot;/g, '"')
        .replace(/&apos;/g, "'")
        .replace(/&amp;/g, '&')
}

function parseStrings(xml) {
    const strings = {}
    const plain = xml.replace(/<!--[\s\S]*?-->/g, '')
    for (const match of plain.matchAll(/<string name="([^"]+)"[^>]*>([\s\S]*?)<\/string>/g)) {
        strings[match[1]] = decode(match[2])
    }
    for (const match of plain.matchAll(/<plurals name="([^"]+)">([\s\S]*?)<\/plurals>/g)) {
        const forms = {}
        for (const item of match[2].matchAll(/<item quantity="([^"]+)">([\s\S]*?)<\/item>/g)) forms[item[1]] = decode(item[2])
        strings[match[1]] = forms
    }
    for (const match of plain.matchAll(/<string-array name="([^"]+)">([\s\S]*?)<\/string-array>/g)) {
        strings[match[1]] = [...match[2].matchAll(/<item>([\s\S]*?)<\/item>/g)].map((item) => decode(item[1]))
    }
    return strings
}

const i18nDir = join(root, 'src/core/i18n/strings')
mkdirSync(i18nDir, { recursive: true })
const untranslated = parseStrings(readFileSync(join(res, 'values/donottranslate.xml'), 'utf8'))
for (const [language, folder] of Object.entries(languages)) {
    // The usage question and ad texts live in their own file, shared with the mobile app's wording.
    const strings = {
        ...parseStrings(readFileSync(join(res, folder, 'strings.xml'), 'utf8')),
        ...parseStrings(readFileSync(join(res, folder, 'strings_usage.xml'), 'utf8')),
        ...parseStrings(readFileSync(join(coreRes, folder, 'strings.xml'), 'utf8')),
    }
    const merged = language === 'en' ? { ...untranslated, ...strings } : strings
    writeFileSync(join(i18nDir, `${language}.json`), `${JSON.stringify(merged, null, 2)}\n`)
    console.log(`${language}: ${Object.keys(merged).length} strings`)
}

function attribute(element, name) {
    return new RegExp(`android:${name}="([^"]*)"`).exec(element)?.[1]
}

function toSvgColor(color) {
    if (!color) return 'none'
    return /^#(FF)?FFFFFF$/i.test(color) ? 'currentColor' : `#${color.slice(-6)}`
}

const icons = {}
for (const file of readdirSync(join(res, 'drawable'))) {
    if (!file.startsWith('ic_') || file.startsWith('ic_launcher')) continue
    const xml = readFileSync(join(res, 'drawable', file), 'utf8')
    const viewBox = `0 0 ${attribute(xml, 'viewportWidth')} ${attribute(xml, 'viewportHeight')}`
    const paths = [...xml.matchAll(/<path\b[\s\S]*?\/>/g)].map(([element]) => {
        const parts = [`d="${attribute(element, 'pathData')}"`]
        parts.push(`fill="${toSvgColor(attribute(element, 'fillColor'))}"`)
        const stroke = attribute(element, 'strokeColor')
        if (stroke) {
            parts.push(`stroke="${toSvgColor(stroke)}"`, `stroke-width="${attribute(element, 'strokeWidth') ?? 1}"`)
            parts.push(`stroke-linecap="${attribute(element, 'strokeLineCap') ?? 'butt'}"`)
            parts.push(`stroke-linejoin="${attribute(element, 'strokeLineJoin') ?? 'miter'}"`)
        }
        return `<path ${parts.join(' ')}/>`
    })
    const name = file.replace(/^ic_/, '').replace(/\.xml$/, '').replace(/_(\w)/g, (_, letter) => letter.toUpperCase())
    icons[name] = { viewBox, body: paths.join('') }
}
const iconSource = `// Generated by scripts/import-android-resources.mjs from the Android app's vector drawables.
export const icons = ${JSON.stringify(icons, null, 4)} as const

export type IconName = keyof typeof icons
`
writeFileSync(join(root, 'src/core/design/icons.ts'), iconSource)
console.log(`icons: ${Object.keys(icons).length}`)

mkdirSync(join(root, 'public/images'), { recursive: true })
copyFileSync(join(res, 'drawable-nodpi/auth_background.webp'), join(root, 'public/images/auth_background.webp'))
console.log('auth background copied')
